#include "../src/core/kms_hidparse.h"
#include <stdio.h>
int fails;
#define CHECK(c) do { if (!(c)) { printf("FAIL %s:%d %s\n", __FILE__, __LINE__, #c); fails++; } } while (0)
int main(void) {
    // Logitech G-series style: report ID 2, 16 buttons, 12-bit X/Y, wheel, AC pan
    static const uint8_t logi[] = {
        0x05,0x01,0x09,0x02,0xA1,0x01,0x85,0x02,0x09,0x01,0xA1,0x00,0x05,0x09,0x19,0x01,0x29,0x10,0x15,0x00,0x25,0x01,
        0x95,0x10,0x75,0x01,0x81,0x02,0x05,0x01,0x16,0x01,0xF8,0x26,0xFF,0x07,0x75,0x0C,0x95,0x02,0x09,0x30,0x09,0x31,
        0x81,0x06,0x15,0x81,0x25,0x7F,0x75,0x08,0x95,0x01,0x09,0x38,0x81,0x06,0x05,0x0C,0x0A,0x38,0x02,0x95,0x01,0x81,0x06,
        0xC0,0xC0};
    kms_mouse_desc_t m; kms_mouse_in_t in;
    CHECK(kms_hid_parse_mouse(logi, sizeof logi, &m) && m.report_id == 2 && !m.absolute);
    CHECK(m.buttons.bit == 0 && m.buttons.size == 16 && m.x.bit == 16 && m.x.size == 12 && m.y.bit == 28 && m.wheel.bit == 40 && m.pan.bit == 48);
    // buttons 1+3, x = -5, y = +300, wheel -1, pan 1
    uint16_t x = (uint16_t)(-5 & 0xFFF), y = 300;
    uint8_t rep[] = {2, 0x05, 0x00, (uint8_t)x, (uint8_t)((x >> 8) | (y << 4)), (uint8_t)(y >> 4), 0xFF, 0x01};
    CHECK(kms_hid_read_mouse(&m, rep, sizeof rep, &in) && in.buttons == 5 && in.x == -5 && in.y == 300 && in.wheel == -1 && in.pan == 1);
    rep[0] = 3; CHECK(!kms_hid_read_mouse(&m, rep, sizeof rep, &in));
    // boot-style mouse without report IDs: 3 buttons + 5 pad, x, y, wheel
    static const uint8_t boot[] = {0x05,0x01,0x09,0x02,0xA1,0x01,0x09,0x01,0xA1,0x00,0x05,0x09,0x19,0x01,0x29,0x03,0x15,0x00,
        0x25,0x01,0x95,0x03,0x75,0x01,0x81,0x02,0x95,0x01,0x75,0x05,0x81,0x01,0x05,0x01,0x09,0x30,0x09,0x31,0x09,0x38,
        0x15,0x81,0x25,0x7F,0x75,0x08,0x95,0x03,0x81,0x06,0xC0,0xC0};
    CHECK(kms_hid_parse_mouse(boot, sizeof boot, &m) && m.report_id == 0 && m.x.bit == 8 && m.wheel.bit == 24);
    uint8_t r2[] = {0x02, 0x10, 0xF0, 0x01};
    CHECK(kms_hid_read_mouse(&m, r2, 4, &in) && in.buttons == 2 && in.x == 16 && in.y == -16 && in.wheel == 1);
    printf("hidparse: %s\n", fails ? "FAILED" : "ok");
    return fails != 0;
}
