#!/usr/bin/env python3
"""kmswitch release tool.

  kmsfw.py keygen KEYFILE                         new Ed25519 release key (keep KEYFILE offline!) and KEYFILE.pub
  kmsfw.py pubc KEYFILE.pub OUT.c                 public key as C source (built into the firmware)
  kmsfw.py pack --board A --version 1.2.0 --key KEYFILE [--allow-downgrade] -o OUT.kmsfw \\
                pc1:0=a0.bin pc1:1=a1.bin pc2:0=b0.bin pc2:1=b1.bin
  kmsfw.py uf2 OUT.uf2 0x10000000=boot.bin 0x1000A000=app.bin 0x10008000=@ff:8192   recovery image (BOOTSEL drive)

Bundle layout: docs/firmware-update.md.
"""
import argparse, hashlib, struct, sys

HEADER = 4096
SIG_OFF = 4032


def keygen(path):
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from cryptography.hazmat.primitives import serialization as s
    k = Ed25519PrivateKey.generate()
    open(path, 'wb').write(k.private_bytes(s.Encoding.Raw, s.PrivateFormat.Raw, s.NoEncryption()))
    open(path + '.pub', 'wb').write(k.public_key().public_bytes(s.Encoding.Raw, s.PublicFormat.Raw))
    print('wrote', path, 'and', path + '.pub')


def pubc(pub, out):
    k = open(pub, 'rb').read()
    assert len(k) == 32
    open(out, 'w').write('// generated by tools/kmsfw.py pubc\n#include <stdint.h>\nconst uint8_t kms_release_pubkey[32] = {%s};\n'
                         % ', '.join('0x%02x' % b for b in k))


def sign(key, msg):
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    return Ed25519PrivateKey.from_private_bytes(open(key, 'rb').read()).sign(msg)


def pack(board, version, key, allow_downgrade, out, images):
    ver = [int(x) for x in version.split('.')]
    assert len(ver) == 3
    entries, blobs, off = [], [], HEADER
    for spec in images:
        what, path = spec.split('=', 1)
        role, slot = what.split(':')
        data = open(path, 'rb').read()
        entries.append(struct.pack('<BBHII', {'pc1': 0, 'pc2': 1}[role], int(slot), 0, off, len(data)) + hashlib.sha256(data).digest())
        blobs.append(data + b'\xff' * (-len(data) % 4096))
        off += len(blobs[-1])
    hdr = b'KMSFW1\0\0' + board.encode() + b'\0\0\0' + struct.pack('<HHHHII', ver[0], ver[1], ver[2], 0,
                                                                     1 if allow_downgrade else 0, len(entries))
    hdr += b''.join(entries)
    hdr += b'\0' * (SIG_OFF - len(hdr))
    hdr += sign(key, hdr)
    assert len(hdr) == HEADER
    open(out, 'wb').write(hdr + b''.join(blobs))
    print('wrote', out, len(hdr) + sum(map(len, blobs)), 'bytes')


def uf2(out, parts):
    blocks = []
    for spec in parts:
        addr, path = spec.split('=', 1)
        addr = int(addr, 0)
        data = b'\xff' * int(path[4:]) if path.startswith('@ff:') else open(path, 'rb').read()
        data += b'\0' * (-len(data) % 256)
        for i in range(0, len(data), 256):
            blocks.append((addr + i, data[i:i + 256]))
    with open(out, 'wb') as f:
        for n, (a, d) in enumerate(blocks):
            f.write(struct.pack('<IIIIIIII', 0x0A324655, 0x9E5D5157, 0x2000, a, 256, n, len(blocks), 0xE48BFF56)
                    + d + b'\0' * (476 - 256) + struct.pack('<I', 0x0AB16F30))
    print('wrote', out, len(blocks), 'blocks')


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return
    cmd, rest = sys.argv[1], sys.argv[2:]
    if cmd == 'keygen':
        keygen(rest[0])
    elif cmd == 'pubc':
        pubc(rest[0], rest[1])
    elif cmd == 'uf2':
        uf2(rest[0], rest[1:])
    elif cmd == 'pack':
        p = argparse.ArgumentParser(prog='kmsfw.py pack')
        p.add_argument('--board', required=True, choices=['A', 'B'])
        p.add_argument('--version', required=True)
        p.add_argument('--key', required=True)
        p.add_argument('--allow-downgrade', action='store_true')
        p.add_argument('-o', required=True)
        p.add_argument('images', nargs='+')
        a = p.parse_args(rest)
        pack(a.board, a.version, a.key, a.allow_downgrade, a.o, a.images)
    else:
        print(__doc__)


if __name__ == '__main__':
    main()
